"""Miami-Dade label validation: one plain-text dossier per case for the reviewers (NYC plan §17;
feasibility/miami/audit/label_validation/PROTOCOL_v2.md). No InSAR file is opened.

Reads the raw viewer pages (--raw, outside the project) and the bulk case data, and writes <case>.txt per case to --out,
also outside the project, because dossiers keep the free text. Every line carries an ID that reviewers cite with their
supporting passages:
  H  header (case details from the viewer, address and point from the bulk data)
  T  free text on the details page (alleged violation, comments)
  V  violation codes with their standard descriptions and dates
  S  structures (the damage assessment per structure)
  A  activities in date order (issue date, code, standard description, structure, comment)
  F  other cases on the same folio, and every case number cited in the text, from the bulk data
Redaction (best effort; the dossiers still stay outside the project): the case's own Inspector, Violator and Owner Name
values, e-mail addresses, phone numbers and "Mr./Ms./Mrs./Dr." with the capitalised words after it become [name],
[email] and [phone]. Routine system rows (holds, mail tracking, payments, recordings, billing) are left out unless they
are report approvals, rejections, exemptions, openings or closings; so are administrative rows (photos, hold checks,
title searches, notices of violation approved by the system, billing, liens). A comment repeated word for word is shown
once and then cited by its line ID.
Run from Alex/:  python3 -I feasibility/miami_case_dossier.py --raw <dir> --out <dir> CASE [CASE ...]
"""
import argparse
import glob
import html
import json
import re
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent / "miami"
SYSTEM = re.compile(r"^(Triggered|System added|This is triggered|Added by BSSNet|USPS Tracking|Recorded on Book|"
                    r"Check: EFUS|Total Number of structures|US NOV sent|Generated by Board|Signature Received for USPS|"
                    r"Cash/Credit Payment|BSS Daily Payment|Submitted (To|by) Finance|Collected by Finance|"
                    r"Based on Recordation data|Electronic Recording requested)", re.I)
ADMIN_CODE = re.compile(r"^(127|110[A-Z0-9]*|119X[A-Z]*|119A[A-Z]*|N7|5[48][A-Z0-9]*|17[A-Z0-9]+|728A|52EK|19EA)$")
ALWAYS = re.compile(r"APPROV|REJECT|DISAPPROV|EXEMPT|CLOSE|OPENED|IN ERROR|COMPLIANCE|DEMOLI|MIGRATED|DAMAGE", re.I)
CASE_RE = re.compile(r"\b((?:CF|F|G)\d{10}|\d{11}|\d{10})(?:-?[A-Z]{1,2})?\b")
TITLE = re.compile(r"\b(Mr|Ms|Mrs|Miss|Dr)\.?\s+(?:[A-Z][\w'’-]*\.?\s*){1,3}")
EMAIL = re.compile(r"[\w.+-]+@[\w-]+(\.[\w-]+)+|\[email[^\]]*\]")
PHONE = re.compile(r"\(?\b\d{3}\)?[\s.-]?\d{3}[\s.-]\d{4}\b")


def text(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s))).strip()


def table(page):
    body = re.search(r"<tbody>(.*?)</tbody>", page, re.S)
    if not body:
        return []
    return [[text(td) for td in re.findall(r"<td[^>]*>(.*?)</td>", tr, re.S)]
            for tr in re.findall(r"<tr>(.*?)</tr>", body.group(1), re.S)]


def field(page, k):
    m = re.search(r"<strong>\s*" + re.escape(k) + r"\s*</strong>\s*(?:</p>)?\s*<p>(.*?)</p>", page, re.S)
    return text(m.group(1)) if m else ""


def iso(d):
    try:
        return datetime.strptime(d, "%m/%d/%Y").strftime("%Y-%m-%d")
    except ValueError:
        return d


def bulk():
    rows = []
    for f in sorted(glob.glob(str(ROOT / "downloads" / "building_violations" / "pages" / "*.geojson"))):
        for x in json.load(open(f))["features"]:
            p = x["properties"]
            p["xy"] = x["geometry"]["coordinates"] if x.get("geometry") else None
            rows.append(p)
    return rows


def day(ms):
    return datetime.fromtimestamp(ms / 1000, timezone.utc).strftime("%Y-%m-%d") if ms else ""


def dossier(cn, raw, by_case, by_folio):
    pg = {t: (raw / f"{cn}_{t}.html").read_text(encoding="utf-8", errors="replace")
          for t in ("USCaseDetails", "ViolationsUS", "StructuresInfo", "ActivitiesUS")}
    d = pg["USCaseDetails"]
    names = sorted({v for k in ("Inspector", "Violator", "Owner Name") for v in [field(d, k)] if len(v) >= 4},
                   key=len, reverse=True)

    def red(s):
        for n in names:
            s = re.sub(re.escape(n), "[name]", s, flags=re.I)
        s = EMAIL.sub("[email]", s)
        s = PHONE.sub("[phone]", s)
        return TITLE.sub("[name] ", s).strip()

    b = by_case.get(cn, {})
    out = [f"CASE {cn}",
           f"H1 case type: {field(d, 'Case Type')} | open date: {iso(field(d, 'Open Date'))} | "
           f"closed: {iso(field(d, 'Date Closed')) or '-'} | folio: {field(d, 'Folio Number')}",
           f"H2 address (bulk data): {(b.get('PROP_ADDR') or '').strip()} | point: {b.get('xy')} | "
           f"permit number: {field(d, 'Permit Number') or '-'}"]
    for i, k in enumerate(("Alleged Violation", "Comments"), 1):
        out.append(f"T{i} {k.lower()}: {red(field(d, k)) or '-'}")
    for i, r in enumerate(table(pg["ViolationsUS"]), 1):
        out.append(f"V{i} {r[1]} | date {iso(r[2])}")
    for i, r in enumerate(table(pg["StructuresInfo"]), 1):
        out.append(f"S{i} structure {r[1]} | {r[2]} | action: {r[3]} | compliance: {r[4]} | {red(r[5])}")
    acts = table(pg["ActivitiesUS"])[::-1]  # the viewer lists newest first
    kept, first = 0, {}
    for i, r in enumerate(acts, 1):
        c = red(r[8] or "")
        if c and SYSTEM.match(c) and not ALWAYS.search(r[2]):
            continue
        if not c and not ALWAYS.search(r[2]):
            continue
        if ADMIN_CODE.match(r[1]) and not ALWAYS.search(r[2]):
            continue
        kept += 1
        st = f" | structure {r[3]}" if r[3] else ""
        if c and c in first:
            c = f"(same text as {first[c]})"
        elif c:
            first[c] = f"A{i}"
        out.append(f"A{i} {iso(r[4])} | {r[1]} {r[2]}{st} | {c or '-'}")
    out.append(f"(activities: {len(acts)} in the record, {kept} shown; routine system rows left out)")
    cited = {m for s in out for m in CASE_RE.findall(s)} - {cn}
    same = [x for x in by_folio.get(b.get("FOLIO"), []) if x["CASE_NUM"] != cn and x["CASE_TYPE"] == "Unsafe Structure"]
    seen = set()
    for x in sorted(same, key=lambda x: x["OPEN_DATE"] or 0) + [by_case[c] for c in sorted(cited) if c in by_case]:
        if x["CASE_NUM"] in seen:
            continue
        seen.add(x["CASE_NUM"])
        how = "same folio" if x.get("FOLIO") == b.get("FOLIO") else "cited, other folio"
        out.append(f"F{len(seen)} {x['CASE_NUM']} | {x['CASE_TYPE']} | open {day(x['OPEN_DATE'])} | "
                   f"closed {day(x['CLOSED_DATE']) or '-'} | {(x.get('PROP_ADDR') or '').strip()} | {how}")
    for c in sorted(cited - set(by_case)):
        out.append(f"F- {c} cited in the text, not in the bulk data")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("cases", nargs="+")
    a = ap.parse_args()
    raw, out = Path(a.raw).resolve(), Path(a.out).resolve()
    assert ROOT.parent.parent not in out.parents, "dossiers keep free text: write them outside the project"
    out.mkdir(parents=True, exist_ok=True)
    rows = bulk()
    by_case = {r["CASE_NUM"]: r for r in rows}
    by_folio = defaultdict(list)
    for r in rows:
        by_folio[r["FOLIO"]].append(r)
    for cn in a.cases:
        (out / f"{cn}.txt").write_text(dossier(cn, raw, by_case, by_folio))


if __name__ == "__main__":
    main()
