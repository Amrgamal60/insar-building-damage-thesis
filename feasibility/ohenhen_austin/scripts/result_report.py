def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def manifest():
    out = {}
    for line in (HERE / "freeze/MANIFEST.sha256").read_text().splitlines():
        h, name = line.split(maxsplit=1)
        out[name] = h
    return out


def b(x, edge):
    return edge if x is None else f"{x:.2f}"


def iv(d, lv):
    return f"{b(d[f'lo{lv}'], '<0.2')} to {b(d[f'hi{lv}'], '>5')}"


def fp(p):
    return "<0.0001" if p < 1e-4 else f"{p:.4g}"


def pct(x, n=1):
    return f"{100 * x:.{n}f}%"


def n(x):
    return f"{x:,.0f}"


def rd(x):
    return "beyond the grid" if x is None else f"{x:.2f}"


